static fp32 ecd_zero(uint16_t ecd, uint16_t offset_ecd, uint16_t ecd_range)
{
		int32_t relative_ecd = ecd - offset_ecd;
		uint16_t half_ecd_range = ecd_range / 2;
	
		if(relative_ecd > half_ecd_range)
		{
					relative_ecd -= ecd_range;
		}
		if(relative_ecd < - half_ecd_range)
		{
					relative_ecd += ecd_range;
		}

		return relative_ecd;
}

fp32 angle_zero(fp32 angle, fp32 offset_angle)
{
		fp32 relative_angle = angle - offset_angle;

		if(relative_angle >  1.25f * PI)
		{
					relative_angle -= 2*PI;
		}
		else if(relative_angle < - 1.25f * PI)
		{
					relative_angle += 2*PI;		
		}

		return relative_angle;
}


void SMC_Init(SMC* smc, float C, float K, float ref, float error_eps, float u_max, float J, float epsilon) 
{
    smc->C = C;                 //相当于P
    smc->K = K;                 //相当于D
    smc->ref = ref;             //目标值
    smc->error_eps = error_eps; //差值死区阈值
    smc->u_max = u_max;         //输出限幅
    smc->J = J;                 //转动惯量
    smc->epsilon = epsilon;     //

    // 初始化状态
    smc->angle = 0;
    smc->ang_vel = 0;
    smc->u = 0;
    smc->error = 0;
    smc->error_last = 0;
    smc->dref = 0;
    smc->ddref = 0;
    smc->refl = 0;
    smc->s = 0;
}

void SMC_Tick(SMC* smc, float angle_now, float angle_vel) 
{
	  if (!smc) return; // 空指针保护

    smc->angle = angle_now;
    smc->ang_vel = angle_vel;
    smc->error = angle_now - smc->ref;
    smc->ddref = (smc->ref - smc->refl) - smc->dref;
    smc->dref = smc->ref - smc->refl;

    if (fabsf(smc->error) < smc->error_eps)
		{
        smc->u = 0;
        return;
    }

    smc->s = smc->C * smc->error + (angle_vel - smc->dref);
    smc->u = smc->J * (smc->ddref - smc->C * (angle_vel - smc->dref) - smc->epsilon * Sat(smc->s) - smc->K * smc->s);

    if (smc->u > smc->u_max) smc->u = smc->u_max;
    if (smc->u < -smc->u_max) smc->u = -smc->u_max;

    smc->refl = smc->ref;
}

static float Sat(float y) 
{
    if (fabsf(y) <= 1.0f)
        return y;
    else
        return (float)Signal(y);
}

static int8_t Signal(float y) 
{
    if (y > 0)
        return 1;
    else if (y < 0)
        return -1;
    else
        return 0;
}



